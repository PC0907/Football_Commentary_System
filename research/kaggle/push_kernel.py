"""Build a self-contained Kaggle kernel (research code embedded as base64) and push it.

  python kaggle/push_kernel.py pitchgeo   NAME "<train_pitchgeo.py args>"
  python kaggle/push_kernel.py commentary NAME "<train_commentary_lora.py args>" ["<commentary_llm.py args>"]

pitchgeo   : downloads SN-Calibration-2023 from HF, trains PitchGeo -> /kaggle/working/run
commentary : downloads MatchTime labels + SN Labels-v2 from HF, builds the dataset, QLoRA-
             fine-tunes, then generates + scores test captions -> /kaggle/working/
Fetch outputs: kaggle kernels output gk8247/NAME -p DIR  (scripts/kaggle_watch.py does this).
"""
import base64, io, json, shutil, subprocess, sys, zipfile
from pathlib import Path

R = Path(__file__).resolve().parents[1]
task, name, args = sys.argv[1], sys.argv[2], sys.argv[3]
gen_args = sys.argv[4] if len(sys.argv) > 4 else ""

buf = io.BytesIO()
with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
    for sub in ("fcs", "scripts"):
        for p in (R / sub).rglob("*.py"):
            z.write(p, p.relative_to(R))
code_b64 = base64.b64encode(buf.getvalue()).decode()

HEAD = f'''# Auto-generated by research/kaggle/push_kernel.py ({task}) — do not edit by hand.
import base64, io, os, subprocess, sys, zipfile, shutil, glob
CODE = "{code_b64}"
os.makedirs("/kaggle/temp/code", exist_ok=True)
zipfile.ZipFile(io.BytesIO(base64.b64decode(CODE))).extractall("/kaggle/temp/code")
def run(cmd, **kw):
    print(">>", " ".join(cmd), flush=True); subprocess.run(cmd, check=True, **kw)
def hf_get(repo, f, local_dir, tries=8):
    """hf_hub_download with backoff (HF CDN returns 429 under load)."""
    import time
    from huggingface_hub import hf_hub_download
    for k in range(tries):
        try:
            return hf_hub_download(repo, f, repo_type="dataset", local_dir=local_dir)
        except Exception as e:
            print("download retry", k, f, repr(e)[:200], flush=True); time.sleep(min(600, 30 * 2 ** k))
    raise RuntimeError("download failed: " + f)
'''

if task == "pitchgeo":
    BODY = f'''
zips = {{f: hf_get("SoccerNet/SN-Calibration-2023", f, "/kaggle/temp/data")
        for f in ("train.zip", "valid.zip")}}
run([sys.executable, "/kaggle/temp/code/scripts/train_pitchgeo.py", "--train-zip", zips["train.zip"],
     "--valid-zip", zips["valid.zip"], "--out", "/kaggle/working/run"] + {args.split()!r})
'''
elif task == "commentary":
    BODY = f'''
run([sys.executable, "-m", "pip", "install", "-q", "-U", "transformers", "peft", "bitsandbytes", "accelerate", "pycocoevalcap"])
from huggingface_hub import snapshot_download
snapshot_download("Homie0609/MatchTime", repo_type="dataset", local_dir="/kaggle/temp/matchtime")
snapshot_download("SoccerNet/SN-Labels", repo_type="dataset", local_dir="/kaggle/temp/labels",
                  allow_patterns=["*Labels-v2.json"])
env = dict(os.environ, MATCHTIME_ROOT="/kaggle/temp/matchtime", SN_LABELS_ROOT="/kaggle/temp/labels",
           PYTORCH_CUDA_ALLOC_CONF="expandable_segments:True")
build = """
import sys, json, os; sys.path.insert(0, '/kaggle/temp/code')
from fcs.commentary.dataset import build_split
os.makedirs('/kaggle/temp/code/cache/commentary', exist_ok=True)
for sp in ('train', 'valid', 'test'):
    ex = build_split(sp)
    with open(f'/kaggle/temp/code/cache/commentary/{{sp}}.jsonl', 'w') as f:
        for e in ex: f.write(json.dumps(e) + chr(10))
    print(sp, len(ex))
"""
run([sys.executable, "-c", build], env=env)
run([sys.executable, "/kaggle/temp/code/scripts/train_commentary_lora.py", "--out", "/kaggle/working/lora"] + {args.split()!r}, env=env)
gen = {gen_args.split()!r}
if gen:
    run([sys.executable, "/kaggle/temp/code/scripts/commentary_llm.py", "--adapter", "/kaggle/working/lora/adapter"] + gen, env=env)
    for f in glob.glob("/kaggle/temp/code/outputs/commentary/*"):
        shutil.copy(f, "/kaggle/working/")
'''
elif task == "detector":
    BODY = f'''
run([sys.executable, "-m", "pip", "install", "-q", "-U", "ultralytics", "rfdetr[train,loggers]"])
for f in ("train.zip", "test.zip"):
    p = hf_get("SoccerNet/SN-Tracking-2023", f, "/kaggle/temp/zips")
    run(["unzip", "-q", p, "-d", "/kaggle/temp/snmot"]); os.remove(p)
run([sys.executable, "/kaggle/temp/code/scripts/train_detector_snmot.py", "--snmot", "/kaggle/temp/snmot",
     "--out", "/kaggle/working/det"] + {args.split()!r})
'''
elif task == "balldata":
    # CPU-only (no GPU quota): fovea training crops from SNMOT train, tuning sequences excluded
    BODY = f'''
p = hf_get("SoccerNet/SN-Tracking-2023", "train.zip", "/kaggle/temp/zips")
run(["unzip", "-q", p, "-d", "/kaggle/temp/snmot"]); os.remove(p)
run([sys.executable, "/kaggle/temp/code/scripts/extract_ball_crops.py", "--snmot", "/kaggle/temp/snmot", "--split", "train",
     "--out", "/kaggle/working/ball_crops.zip", "--exclude-tuning"] + {args.split()!r})
'''
else:
    sys.exit(f"unknown task {task}")

d = R / "kaggle" / "build" / name
if d.exists():
    shutil.rmtree(d)
d.mkdir(parents=True)
(d / "kernel.py").write_text(HEAD + BODY)
(d / "kernel-metadata.json").write_text(json.dumps({
    "id": f"gk8247/{name}", "title": name, "code_file": "kernel.py", "language": "python",
    "kernel_type": "script", "is_private": True, "enable_gpu": task != "balldata", "enable_internet": True,
    "dataset_sources": [], "competition_sources": [], "kernel_sources": []}))
if "--build-only" in sys.argv:
    # hand-off package: a one-cell notebook another person can import and run on their own account
    nb = {"cells": [{"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
                     "source": (HEAD + BODY).splitlines(keepends=True)}],
          "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}},
          "nbformat": 4, "nbformat_minor": 5}
    (d / f"{name}.ipynb").write_text(json.dumps(nb))
    print("built", d / f"{name}.ipynb")
    sys.exit(0)
kag = str(Path(sys.executable).with_name("kaggle"))
r = subprocess.run([kag, "kernels", "push", "-p", str(d)], capture_output=True, text=True)
print(r.stdout[-800:], r.stderr[-800:])
